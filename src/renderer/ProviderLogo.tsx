function brandKey(providerId: string | null | undefined, label: string): string | null {
  const value = `${providerId ?? ""} ${label}`.toLowerCase();
  if (/openai|chatgpt|codex/.test(value)) return "openai";
  if (/anthropic|claude/.test(value)) return "anthropic";
  if (/google|gemini|vertex/.test(value)) return "google";
  if (/azure/.test(value)) return "azure";
  if (/mistral/.test(value)) return "mistral";
  if (/openrouter/.test(value)) return "openrouter";
  if (/\bxai\b|grok/.test(value)) return "xai";
  if (/groq/.test(value)) return "groq";
  if (/cohere|command-r/.test(value)) return "cohere";
  return null;
}

export function ProviderLogo({ providerId, label, size = 15 }: ProviderLogoProps) {
  const key = brandKey(providerId, label);
  const brand = key ? BRAND_LOGOS[key] : null;
  if (!brand) return <span className="provider-logo-fallback" aria-hidden="true">{label.trim().charAt(0).toUpperCase() || "·"}</span>;
  return <svg className="provider-logo" width={size} height={size} viewBox="0 0 24 24" fill="currentColor" aria-hidden="true" focusable="false">
    <path fillRule="evenodd" d={brand.path} />
  </svg>;
}
